import type { Route } from '@playwright/test';
import { expect, test } from './fixtures/authenticated';

test.use({ initialServerSettings: { 'autogenerated-passphrase': 'True', 'has-asked-for-password-change': 'False' } });
test.beforeEach(async ({ page, serverApi }) => {
  void serverApi;
  await page.route('**/api/v1/systeminfo', (route) =>
    route.fulfill({
      json: {
        Version: 'Browser test',
        DefaultUsageReportLevel: 'information',
        StartedBy: 'Server',
        BackendModules: [],
        EncryptionModules: [],
        CompressionModules: [],
        GenericModules: [],
        Options: [],
        ServerOnlyOptions: [],
        SpecialFolders: [],
        APIExtensions: [
          'v1:websocket',
          'v1:websocket:authenticate',
          'v1:subscribe:backuplist',
          'v1:subscribe:notifications',
          'v1:subscribe:remotecontrol',
        ],
      },
    })
  );
});

test('deferring the initial passphrase change records only the prompt choice', async ({
  authenticatedPage: page,
  serverApi,
}) => {
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('heading', { name: 'Change passphrase', exact: true })).toBeVisible();
  await expect(dialog.getByPlaceholder('Repeat password', { exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Not now thanks', exact: true }).click();
  await expect.poll(() => serverApi.settingsRequests.length).toBe(1);
  expect(serverApi.settingsRequests[0].request().postDataJSON()).toEqual({ 'has-asked-for-password-change': 'True' });
  await expect(dialog).toBeVisible();
  await serverApi.settingsRequests[0].fulfill({ json: {} });
  await expect(dialog).toHaveCount(0);
  await expect(page).toHaveURL('/');
});

test('matching passphrases are saved exactly before the session is signed out', async ({
  authenticatedPage: page,
  serverApi,
}) => {
  const logouts: Route[] = [];
  await page.route('**/api/v1/auth/refresh/logout', (route) => {
    logouts.push(route);
  });
  const dialog = page.getByRole('dialog');
  const password = dialog.getByPlaceholder('Enter new password', { exact: true });
  const repeat = dialog.getByPlaceholder('Repeat password', { exact: true });
  const save = dialog.getByRole('button', { name: 'Yes, update passphrase now', exact: true });
  await expect(repeat).toBeDisabled();
  const value = ' new pass & + % ';
  await password.fill(value);
  await expect(repeat).toBeEnabled();
  await repeat.fill('does not match');
  await expect(save).toBeDisabled();
  await repeat.fill(value);
  await expect(save).toBeEnabled();
  await save.click();
  await expect.poll(() => serverApi.settingsRequests.length).toBe(1);
  expect(serverApi.settingsRequests[0].request().postDataJSON()).toEqual({ 'server-passphrase': value });
  expect(logouts).toHaveLength(0);
  await expect(dialog).toBeVisible();
  await serverApi.settingsRequests[0].fulfill({ json: {} });
  await expect(dialog).toHaveCount(0);
  await expect.poll(() => logouts.length).toBe(1);
  await logouts[0].fulfill({ json: {} });
  await expect(page).toHaveURL('/login');
});
