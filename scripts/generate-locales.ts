import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { DEFAULT_LOCALE, LOCALE_CATALOG, SOURCE_LOCALE, type LocaleDefinition } from './locale-catalog';

const header = '// Generated by scripts/generate-locales.ts. Edit scripts/locale-catalog.ts instead.\n';
const localeDirectory = 'projects/ngclient/src/app/core/locales';
export const messageStem = (locale: LocaleDefinition) => locale.file ?? locale.code.replaceAll('-', '_');

export function validateCatalog(catalog: readonly LocaleDefinition[]) {
  const codes = new Set<string>();
  const aliases = new Set<string>();
  const dayjsKeys = new Set<string>();
  const safe = (value: string) => {
    if (!/^[a-zA-Z0-9]+(?:[-_][a-zA-Z0-9]+)*$/.test(value)) throw new Error('Invalid locale identifier: ' + value);
  };
  for (const entry of catalog) {
    safe(entry.code);
    if (codes.has(entry.code)) throw new Error('Duplicate locale code: ' + entry.code);
    codes.add(entry.code);
  }
  for (const entry of catalog) {
    for (const alias of [entry.code, ...(entry.aliases ?? [])]) {
      safe(alias);
      if (aliases.has(alias)) throw new Error('Duplicate locale alias: ' + alias);
      aliases.add(alias);
    }
    if (entry.runtime && !codes.has(entry.runtime)) throw new Error('Unknown runtime locale: ' + entry.runtime);
    for (const value of [
      entry.file,
      entry.buildFile,
      entry.angular?.data,
      entry.angular?.alias,
      entry.angular?.extra,
      entry.dayjs?.data,
    ]) {
      if (value) safe(value);
    }
    if (entry.dayjs) {
      const key = entry.dayjs.key ?? entry.code.toLowerCase();
      safe(key);
      if (dayjsKeys.has(key)) throw new Error('Duplicate Day.js key: ' + key);
      dayjsKeys.add(key);
    }
  }
  if (!codes.has(DEFAULT_LOCALE) || !codes.has(SOURCE_LOCALE.code)) throw new Error('Default/source locale is missing');
}

export function buildLocaleArtifacts(configuration: any, catalog: readonly LocaleDefinition[] = LOCALE_CATALOG) {
  validateCatalog(catalog);
  const definitions = {
    DEFAULT_LOCALE,
    LANGUAGES: catalog.filter((e) => e.label !== undefined).map((e) => ({ value: e.code, label: e.label })),
    LOCALE_MAP: Object.fromEntries(
      catalog.flatMap((e) => [e.code, ...(e.aliases ?? [])].map((code) => [code, e.runtime ?? e.code]))
    ),
    ANGULAR_MJS_LOCALE_MAP: Object.fromEntries(
      catalog.filter((e) => e.angular?.alias).map((e) => [e.code, e.angular!.alias])
    ),
  };
  const angular = new Map<string, string>();
  const extra = new Map<string, string>();
  const dayjs = new Map<string, string>();
  const set = (map: Map<string, string>, key: string, value: string) => {
    if (map.has(key) && map.get(key) !== value) throw new Error('Conflicting locale data: ' + key);
    map.set(key, value);
  };
  for (const entry of catalog) {
    if (entry.angular) {
      const key = entry.angular.alias ?? entry.code;
      set(angular, key, entry.angular.data);
      if (entry.angular.extra) set(extra, key, entry.angular.extra);
    }
    if (entry.dayjs) set(dayjs, entry.dayjs.key ?? entry.code.toLowerCase(), entry.dayjs.data);
  }
  const module = (maps: [string, Map<string, string>, string][], prefix = '') => {
    const imports = new Map<string, string>();
    for (const [, map, path] of maps)
      for (const value of map.values()) {
        const specifier = path + value;
        if (!imports.has(specifier)) imports.set(specifier, 'locale' + imports.size);
      }
    return (
      prefix +
      header +
      [...imports].map(([path, name]) => 'import ' + name + ' from ' + JSON.stringify(path) + ';').join('\n') +
      '\n\n' +
      maps
        .map(
          ([name, map, path]) =>
            'export const ' +
            name +
            (name === 'DAYJS_LOCALES' ? ': Record<string, ILocale>' : ': Record<string, any>') +
            ' = {\n' +
            [...map].map(([key, value]) => JSON.stringify(key) + ': ' + imports.get(path + value)).join(',\n') +
            '\n};'
        )
        .join('\n\n') +
      '\n'
    );
  };
  const config = structuredClone(configuration);
  const project = config.projects.ngclient;
  project.i18n = {
    sourceLocale: { ...SOURCE_LOCALE },
    locales: Object.fromEntries(
      catalog
        .filter((e) => e.build !== false)
        .map((e) => [
          e.code,
          {
            translation: 'projects/ngclient/src/locale/messages.' + (e.buildFile ?? messageStem(e)) + '.xlf',
            baseHref: e.code,
          },
        ])
    ),
  };
  const assets = project.architect.build.options.assets;
  const messages = assets.find(
    (a: any) => a.input === './projects/ngclient/src/locale' && a.glob.startsWith('messages.{')
  );
  const dayjsAssets = assets.find((a: any) => a.input === './node_modules/dayjs/esm/locale');
  if (!messages || !dayjsAssets) throw new Error('Locale asset configuration is missing');
  messages.glob = 'messages.{' + [...new Set(catalog.map(messageStem))].join(',') + '}.json';
  dayjsAssets.glob =
    '{' +
    [...new Set(catalog.filter((e) => e.dayjs && e.dayjs.asset !== false).map((e) => e.dayjs!.data))].join(',') +
    '}.js';

  const runtime =
    header +
    Object.entries(definitions)
      .map(([name, value]) => {
        const annotation = name === 'LOCALE_MAP' || name === 'ANGULAR_MJS_LOCALE_MAP' ? ': Record<string, string>' : '';
        return 'export const ' + name + annotation + ' = ' + JSON.stringify(value, null, 2) + ';';
      })
      .join('\n\n') +
    '\n';
  return {
    config,
    files: {
      'angular.json': JSON.stringify(config, null, 2) + '\n',
      [localeDirectory + '/locale-definitions.ts']: runtime,
      [localeDirectory + '/angular-locale-data.ts']: module([
        ['ANGULAR_LOCALE_DATA', angular, '@angular/common/locales/'],
        ['ANGULAR_LOCALE_EXTRA_DATA', extra, '@angular/common/locales/extra/'],
      ]),
      [localeDirectory + '/dayjs.const.ts']: module(
        [['DAYJS_LOCALES', dayjs, 'dayjs/esm/locale/']],
        '// @ts-nocheck\n'
      ),
    },
  };
}

export async function verifyLocaleAssets(root: string, configuration: any, catalog = LOCALE_CATALOG) {
  for (const entry of catalog) {
    if (entry.build !== false)
      await access(join(root, configuration.projects.ngclient.i18n.locales[entry.code].translation));
    await access(join(root, 'projects/ngclient/src/locale/messages.' + messageStem(entry) + '.json'));
    if (entry.angular) {
      Bun.resolveSync('@angular/common/locales/' + entry.angular.data, root);
      if (entry.angular.extra) Bun.resolveSync('@angular/common/locales/extra/' + entry.angular.extra, root);
    }
    if (entry.dayjs) Bun.resolveSync('dayjs/esm/locale/' + entry.dayjs.data, root);
  }
  await access(join(root, 'projects/ngclient/src/locale/messages.json'));
}

export async function generateLocales(check = false) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const original = JSON.parse(await readFile(join(root, 'angular.json'), 'utf8'));
  const artifacts = buildLocaleArtifacts(original);
  await verifyLocaleAssets(root, artifacts.config);
  const stale: string[] = [];
  for (const [relative, source] of Object.entries(artifacts.files)) {
    const target = join(root, relative);
    const expected = await format(source, { ...(await resolveConfig(target)), filepath: target });
    const actual = await readFile(target, 'utf8').catch(() => '');
    if (actual === expected) continue;
    stale.push(relative);
    if (!check) {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, expected);
    }
  }
  if (check && stale.length)
    throw new Error('Generated locale definitions are out of date: ' + stale.join(', ') + '. Run bun run gen:locales.');
  console.log(
    check
      ? 'Locale definitions and assets are up to date.'
      : 'Updated locale definitions: ' + (stale.join(', ') || 'none')
  );
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: bun scripts/generate-locales.ts [--check]');
  await generateLocales(args.includes('--check'));
}
